// Builds content/geo/data-design-base.json: the *real* base data shown under the design-mode layers.
// Run by hand; the output is committed. Nothing here runs at site build time.
//
//   node scripts/geo/design-base.mjs <WindFarmsConnected.csv> <irish-rail-gtfs-dir>
//
// <WindFarmsConnected.csv>: SEAI, "Wind Farms in Ireland" (connected, June 2022), CC BY 4.0.
//   https://data.gov.ie/dataset/wind-farms-in-ireland
// <irish-rail-gtfs-dir>: the unzipped Irish Rail GTFS schedule (NTA / Transport for Ireland), CC BY 4.0.
//   https://www.transportforireland.ie/transitData/Data/GTFS_Irish_Rail.zip
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const [windCsv, gtfsDir] = process.argv.slice(2);
if (!windCsv || !gtfsDir) {
  console.error('usage: node scripts/geo/design-base.mjs <WindFarmsConnected.csv> <irish-rail-gtfs-dir>');
  process.exit(1);
}

/** Minimal RFC 4180 parser: quoted fields may contain commas, quotes ("") and line breaks. */
function csv(text) {
  const rows = [[]];
  let cur = '';
  let q = false;
  const t = text.replace(/^\uFEFF/, '');
  for (let i = 0; i < t.length; i++) {
    const ch = t[i];
    if (q) {
      if (ch === '"' && t[i + 1] === '"') (cur += '"'), i++;
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') rows[rows.length - 1].push(cur), (cur = '');
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && t[i + 1] === '\n') i++;
      rows[rows.length - 1].push(cur);
      cur = '';
      rows.push([]);
    } else cur += ch;
  }
  if (cur) rows[rows.length - 1].push(cur);
  const [head, ...body] = rows.filter((r) => r.length > 1);
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

// ---- Wind: maximum export capacity (MW) of connected and energised wind farms, by county.
// MEC is used because "Installed capacity" is blank for many rows in the source.
const wind = csv(await readFile(windCsv, 'utf8'));
const mw = {};
let offshore = 0;
for (const r of wind) {
  const v = Number(r.MEC__MW_) || 0;
  if (r.County === 'Offshore') offshore += v;
  else {
    const id = r.County.toLowerCase();
    mw[id] = (mw[id] || 0) + v;
  }
}
const topo = JSON.parse(await readFile('content/geo/ireland.topo.json', 'utf8'));
const counties = [...new Set(topo.objects.la.geometries.map((g) => g.properties.county_id))];
for (const c of counties) mw[c] = Math.round((mw[c] || 0) * 10) / 10;
for (const k of Object.keys(mw)) if (!counties.includes(k)) throw new Error(`unknown county in wind data: ${k}`);

// ---- Existing passenger rail: shapes from the Irish Rail timetable, longest first, skipping any
// shape that is already 95% covered by those kept, then thinned to one point every ~500 m.
const shapes = new Map();
for (const r of csv(await readFile(join(gtfsDir, 'shapes.txt'), 'utf8'))) {
  if (!shapes.has(r.shape_id)) shapes.set(r.shape_id, []);
  shapes.get(r.shape_id).push([Number(r.shape_pt_sequence), Number(r.shape_pt_lon), Number(r.shape_pt_lat)]);
}
const lines = [...shapes.values()].map((pts) => pts.sort((a, b) => a[0] - b[0]).map(([, x, y]) => [x, y]));
const km = ([x1, y1], [x2, y2]) => Math.hypot((x2 - x1) * 111.32 * Math.cos((y1 * Math.PI) / 180), (y2 - y1) * 110.57);
const length = (l) => l.slice(1).reduce((s, p, i) => s + km(l[i], p), 0);
lines.sort((a, b) => length(b) - length(a));
const cell = ([x, y]) => `${Math.round(x / 0.004)},${Math.round(y / 0.003)}`; // ~270 m × 330 m
const covered = new Set();
const near = (p) => {
  const [cx, cy] = cell(p).split(',').map(Number);
  for (let dx = -1; dx <= 1; dx++) for (let dy = -1; dy <= 1; dy++) if (covered.has(`${cx + dx},${cy + dy}`)) return true;
  return false;
};
const kept = [];
for (const l of lines) {
  const newPts = l.filter((p) => !near(p)).length;
  if (newPts / l.length < 0.05) continue;
  kept.push(l);
  l.forEach((p) => covered.add(cell(p)));
}
const thin = (l) => {
  const out = [l[0]];
  for (const p of l.slice(1, -1)) if (km(out[out.length - 1], p) >= 0.5) out.push(p);
  out.push(l[l.length - 1]);
  return out.map(([x, y]) => [Math.round(x * 1000) / 1000, Math.round(y * 1000) / 1000]);
};
const rail = { type: 'MultiLineString', coordinates: kept.map(thin) };

const stops = csv(await readFile(join(gtfsDir, 'stops.txt'), 'utf8'));
const feed = csv(await readFile(join(gtfsDir, 'feed_info.txt'), 'utf8'))[0] || {};

const out = {
  note: 'Generated by scripts/geo/design-base.mjs. Real data shown as the base of design-mode layers. Do not edit by hand.',
  generated: new Date().toISOString().slice(0, 10),
  wind: {
    period: 'June 2022',
    values: mw,
    offshore_mw: Math.round(offshore * 10) / 10,
    total_mw: Math.round(Object.values(mw).reduce((a, b) => a + b, 0) + offshore),
    farms: wind.length,
    source: { title: 'Wind Farms in Ireland (connected, June 2022)', publisher: 'SEAI', licence: 'CC BY 4.0', url: 'https://data.gov.ie/dataset/wind-farms-in-ireland' },
  },
  rail: {
    geometry: rail,
    stations: stops.length,
    timetable_from: (feed.feed_start_date || '').replace(/(\d{4})(\d{2})(\d{2})/, '$1-$2-$3'),
    source: { title: 'Schedule data for Irish Rail (GTFS)', publisher: 'National Transport Authority / Transport for Ireland', licence: 'CC BY 4.0', url: 'https://data.gov.ie/dataset/gtfs-irish-rail-gtfs' },
  },
};
await writeFile('content/geo/data-design-base.json', JSON.stringify(out));
console.log(`wind: ${out.wind.farms} rows, ${out.wind.total_mw} MW; rail: ${kept.length} of ${lines.length} shapes, ${rail.coordinates.flat().length} points`);
